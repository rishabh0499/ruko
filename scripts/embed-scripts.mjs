// Embeds every line of the scam-script library once and writes data/script-embeddings.js, so the
// app only embeds the customer's sentences at run time. Re-run after editing data/scripts.js.
// Usage: node scripts/embed-scripts.mjs [threshold]
import '../lib/env.js';
import { writeFileSync } from 'node:fs';
import SCRIPTS from '../data/scripts.js';
import { embedTexts, EMBED } from '../lib/gemini.js';
import OLD from '../data/script-embeddings.js';

const threshold = Number(process.argv[2] || OLD.threshold || 0.9);
const lines = SCRIPTS.flatMap((s) => s.lines.map((l) => ({ id: s.id, l })));
const vecs = [];
for (let i = 0; i < lines.length; i += 90) {
  const v = await embedTexts(lines.slice(i, i + 90).map((x) => x.l), { timeoutMs: 30000 });
  if (!v) throw new Error('Embedding failed (quota? wait a minute and retry)');
  vecs.push(...v);
}
const scripts = SCRIPTS.map((s) => ({ id: s.id, vectors: vecs.filter((_, i) => lines[i].id === s.id).map((v) => v.map((x) => Math.round(x * 1e5) / 1e5)) }));
writeFileSync(new URL('../data/script-embeddings.js', import.meta.url), `// Generated by scripts/embed-scripts.mjs: ${EMBED.model}, ${EMBED.dim} dims, ${lines.length} script lines.\n// threshold: calibrated so no sentence in the legitimate eval cases matches (see docs).\nexport default ${JSON.stringify({ model: EMBED.model, dim: EMBED.dim, threshold, scripts })};\n`);
console.log(`data/script-embeddings.js: ${scripts.length} scripts, ${lines.length} lines, threshold ${threshold}`);
