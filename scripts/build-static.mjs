// Builds a server-less Ruko: lib/app.js runs in the browser (public/js/localapi.js).
//   node scripts/build-static.mjs artifact  → dist-artifact/  Claude artifact, offline rules, no key
//   node scripts/build-static.mjs web       → dist-web/       Firebase Hosting, live Gemini from the
//                                              browser with WEB_GEMINI_API_KEY from .env (never committed)
import { cpSync, mkdirSync, rmSync, readFileSync, writeFileSync, readdirSync, statSync, existsSync, copyFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SCENARIOS, repliesFor, callScriptFor } from '../data/scenarios.js';
import { Q, finalMessage } from '../lib/interviewer.js';
import { ttsKey } from '../lib/tts.js';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const TARGET = process.argv[2] === 'web' ? 'web' : 'artifact';
const OUT = join(ROOT, TARGET === 'web' ? 'dist-web' : 'dist-artifact');
const env = Object.fromEntries((existsSync(join(ROOT, '.env')) ? readFileSync(join(ROOT, '.env'), 'utf8') : '').split('\n').map((l) => l.match(/^\s*([A-Z_]+)\s*=\s*(.*)\s*$/)).filter(Boolean).map((m) => [m[1], m[2]]));
// CI has no .env: fall back to environment variables (GitHub Actions secrets).
for (const k of ['WEB_GEMINI_API_KEY', 'GEMINI_MODEL_FAST', 'GEMINI_MODEL_PRO', 'GEMINI_MODEL_TTS']) if (!env[k] && process.env[k]) env[k] = process.env[k];
rmSync(OUT, { recursive: true, force: true });
mkdirSync(join(OUT, 'lib'), { recursive: true });
mkdirSync(join(OUT, 'data'), { recursive: true });
mkdirSync(join(OUT, 'tts'), { recursive: true });

// 1. Frontend, application core and data (no Node-only files).
cpSync(join(ROOT, 'public'), join(OUT, 'public'), { recursive: true });
for (const f of ['app.js', 'policy.js', 'interviewer.js', 'extractor.js', 'casefile.js', 'gemini.js', 'ids.js']) copyFileSync(join(ROOT, 'lib', f), join(OUT, 'lib', f));
for (const f of readdirSync(join(ROOT, 'data'))) if (f.endsWith('.js')) copyFileSync(join(ROOT, 'data', f), join(OUT, 'data', f));

// 2. Voices that were generated with Gemini TTS ship as WAV files with a lookup table.
const lines = [];
for (const scn of Object.values(SCENARIOS)) for (const lang of ['hi', 'en']) {
  lines.push(...Object.values(Q[lang]).map((text) => ({ speaker: 'ruko', text })));
  for (const o of ['proceed', 'proceed_with_warning', 'hold_trusted_contact', 'escalate']) lines.push({ speaker: 'ruko', text: finalMessage(o, lang, { trustedContact: scn.trustedContacts?.[0], top: [] }) });
  lines.push(...repliesFor(scn, lang).map((r) => ({ speaker: scn.speaker, text: r.text })), ...callScriptFor(scn, lang));
}
const manifest = {};
for (const l of lines) {
  const key = ttsKey(l.speaker, l.text);
  // Voiced lines are committed in assets/tts so CI builds have them; new local recordings in
  // store/tts (gitignored) are copied there on each local build.
  const cached = join(ROOT, 'store', 'tts', `${key}.wav`);
  const src = join(ROOT, 'assets', 'tts', `${key}.wav`);
  if (existsSync(cached) && !existsSync(src)) { mkdirSync(join(ROOT, 'assets', 'tts'), { recursive: true }); copyFileSync(cached, src); }
  if (existsSync(src) && !manifest[`${l.speaker}|${l.text}`]) { copyFileSync(src, join(OUT, 'tts', `${key}.wav`)); manifest[`${l.speaker}|${l.text.trim()}`] = `${key}.wav`; }
}
writeFileSync(join(OUT, 'public', 'js', 'tts-manifest.js'), `// Generated by scripts/build-static.mjs\nexport default ${JSON.stringify(manifest, null, 1)};\n`);

// 3. The page.
const html = readFileSync(join(ROOT, 'public', 'index.html'), 'utf8');
if (TARGET === 'web') {
  // A real web page: absolute paths become relative, and the browser gets live Gemini settings.
  const RUKO_ENV = {
    GEMINI_API_KEY: env.WEB_GEMINI_API_KEY || '',
    GEMINI_MODEL_FAST: env.GEMINI_MODEL_FAST || '', GEMINI_MODEL_PRO: env.GEMINI_MODEL_PRO || '', GEMINI_MODEL_TTS: env.GEMINI_MODEL_TTS || '',
  };
  for (const k of Object.keys(RUKO_ENV)) if (!RUKO_ENV[k]) delete RUKO_ENV[k];
  if (!RUKO_ENV.GEMINI_API_KEY) console.warn('WEB_GEMINI_API_KEY is not set in .env: the website will run in offline rules mode.');
  const page = html
    .replace('href="/css/app.css"', 'href="public/css/app.css"')
    .replace('<script type="module" src="/js/main.js"></script>', `<script>window.RUKO_STATIC = true; window.RUKO_ENV = ${JSON.stringify(RUKO_ENV)};</script>\n<script type="module" src="public/js/main.js"></script>`);
  writeFileSync(join(OUT, 'index.html'), page);
} else {
  // The artifact host supplies <html>/<head>/<body>, so keep only our own tags.
  const head = html.slice(html.indexOf('<head>') + 6, html.indexOf('</head>'))
    .split('\n').filter((l) => !/<meta charset|<meta name="viewport"/.test(l)).join('\n')
    .replace('href="/css/app.css"', 'href="public/css/app.css"');
  const body = html.slice(html.indexOf('<body>') + 6, html.indexOf('</body>'))
    .replace('<script type="module" src="/js/main.js"></script>', '<script>window.RUKO_STATIC = true; window.RUKO_ARTIFACT = true;</script>\n<script type="module" src="public/js/main.js"></script>');
  writeFileSync(join(OUT, 'index.html'), `${head.trim()}\n${body.trim()}\n`);
}

// 4. Report.
const walk = (d) => readdirSync(d).flatMap((f) => (statSync(join(d, f)).isDirectory() ? walk(join(d, f)) : [join(d, f)]));
const files = walk(OUT);
const bytes = files.reduce((s, f) => s + statSync(f).size, 0);
console.log(`${TARGET === 'web' ? 'dist-web' : 'dist-artifact'}: ${files.length} files, ${(bytes / 1e6).toFixed(1)} MB, ${Object.keys(manifest).length} voiced lines`);
